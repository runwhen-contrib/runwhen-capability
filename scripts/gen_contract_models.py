#!/usr/bin/env python3
"""Generate pydantic v2 models from contracts/schemas.

    python3 scripts/gen_contract_models.py                 # rewrite the committed models
    python3 scripts/gen_contract_models.py --check         # change nothing; exit 1 on drift
    python3 scripts/gen_contract_models.py --out DIR       # generate somewhere else

One module per schema in src/runwhen_capability/contracts/models/, named after
the schema with `-` and `.` turned into `_` (`rw.access.v1` -> `rw_access_v1.py`,
`compiled-plugin` -> `compiled_plugin.py`); the root class is the schema's
`title`. Shared definitions are in `common.py`.

datamodel-code-generator cannot resolve the schemas' `$id` URLs without the
network, so it runs on a temporary copy where every
`https://schemas.runwhen.com/<name>/v1.json` reference is the relative file of
that schema. The JSON Schema stays the authority: the models are a convenience
and are looser where the generator cannot express a keyword (`if/then`, `not`,
`unevaluatedProperties`, rules across fields).
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SCHEMAS = REPO / "contracts" / "schemas"
DEFAULT_OUT = REPO / "src" / "runwhen_capability" / "contracts" / "models"

HEADER = (
    "# generated by scripts/gen_contract_models.py -- do not edit;"
    " rerun `make contracts-models`.\n"
    "# ruff: noqa: E501\n"
)

INIT = '''"""Pydantic v2 models generated from the contracts' JSON Schemas.

One module per schema (`lease`, `compiled_plugin`, `rw_access_v1`, ...) whose
root class is the schema's title: `from runwhen_capability.contracts.models.lease
import Lease`. Nothing is imported here, so `import ...contracts.models` stays
free; regenerate with `make contracts-models`. The JSON Schemas remain the
authority (`contracts.validate`); the models are looser where the generator
cannot express a keyword.
"""
'''

# Pinned in pyproject.toml's dev extra; the arguments are part of the output.
CODEGEN_ARGS = [
    "--input-file-type",
    "jsonschema",
    "--output-model-type",
    "pydantic_v2.BaseModel",
    "--target-python-version",
    "3.12",
    "--use-standard-collections",
    "--use-union-operator",
    "--field-constraints",
    "--extra-fields",
    "forbid",
    "--use-schema-description",
    "--disable-timestamp",
    # ruff formats the result afterwards; no black/isort needed.
    "--formatters",
    "builtin",
]

_REF = re.compile(r'https://schemas\.runwhen\.com/([^/"#]+)/v1\.json')


def module_name(schema_name: str) -> str:
    return re.sub(r"[-.]", "_", schema_name)


def _prepare_inputs(target: Path) -> None:
    """Copy every schema to <module>.json with `$id` URL refs made relative."""
    for path in sorted(SCHEMAS.glob("*.schema.json")):
        name = path.name.removesuffix(".schema.json")
        text = _REF.sub(lambda m: f"{module_name(m.group(1))}.json", path.read_text("utf-8"))
        doc = json.loads(text)
        doc.pop("$id", None)
        (target / f"{module_name(name)}.json").write_text(json.dumps(doc, indent=2), "utf-8")


def _run(*cmd: str, cwd: Path) -> None:
    done = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if done.returncode:
        sys.stderr.write(done.stdout + done.stderr)
        raise SystemExit(f"{' '.join(cmd[:3])} failed (exit {done.returncode})")


def generate(out: Path) -> None:
    """Write a fresh models package into `out` (replacing generated modules)."""
    with tempfile.TemporaryDirectory(prefix="gen-contract-models-") as tmp:
        work = Path(tmp)
        (work / "in").mkdir()
        (work / "out").mkdir()
        _prepare_inputs(work / "in")
        _run(
            sys.executable,
            "-m",
            "datamodel_code_generator",
            "--input",
            str(work / "in"),
            "--output",
            str(work / "out"),
            *CODEGEN_ARGS,
            cwd=work,
        )
        generated = work / "out"
        # Re-exporting every class from __init__ would import them all eagerly.
        (generated / "__init__.py").write_text(INIT, "utf-8")
        for path in sorted(generated.glob("*.py")):
            if path.name == "__init__.py":
                continue
            body = re.sub(r"\A(?:#[^\n]*\n)+\n*", "", path.read_text("utf-8"))
            path.write_text(HEADER + "\n" + body, "utf-8")
        config = str(REPO / "pyproject.toml")
        ruff = [sys.executable, "-m", "ruff"]
        # Fix, then format: removing an import can change what the formatter wants.
        _run(
            *ruff, "check", "--config", config, "--fix", "--select", "I,UP,F401", "--quiet",
            str(generated), cwd=work,
        )  # fmt: skip
        _run(*ruff, "format", "--config", config, "--quiet", str(generated), cwd=work)

        out.mkdir(parents=True, exist_ok=True)
        for stale in out.glob("*.py"):
            stale.unlink()
        for path in sorted(generated.glob("*.py")):
            shutil.copyfile(path, out / path.name)


def _tree(root: Path) -> dict[str, bytes]:
    if not root.is_dir():
        return {}
    return {p.name: p.read_bytes() for p in sorted(root.glob("*.py"))}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="directory to write")
    parser.add_argument(
        "--check", action="store_true", help="write nothing; exit 1 if --out is out of date"
    )
    args = parser.parse_args(argv)
    if not args.check:
        generate(args.out)
        print(f"wrote {len(_tree(args.out))} modules to {args.out}")
        return 0
    with tempfile.TemporaryDirectory(prefix="gen-contract-models-check-") as tmp:
        fresh_dir = Path(tmp) / "models"
        generate(fresh_dir)
        fresh, current = _tree(fresh_dir), _tree(args.out)
    drift = sorted(
        name for name in fresh.keys() | current.keys() if fresh.get(name) != current.get(name)
    )
    for name in drift:
        print(f"out of date: {name}", file=sys.stderr)
    if drift:
        print("run `python3 scripts/gen_contract_models.py`", file=sys.stderr)
    return 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main())
