def _module_name(name: str) -> str:
    return name.replace("-", "_").replace(".", "_")


def _root_model(name: str) -> type[pydantic.BaseModel]:
    module = importlib.import_module(f"runwhen_capability.contracts.models.{_module_name(name)}")
    return getattr(module, schema(name)["title"])


def _model_of(path: Path) -> type[pydantic.BaseModel]:
    """The model a fixture is an instance of: its schema's root class, or the class generated
    for the `$defs` entry (`materializedCredential` -> `MaterializedCredential`)."""
    def_name = def_of(path)
    if def_name is None:
        return _root_model(schema_of(path))
    module = importlib.import_module(
        f"runwhen_capability.contracts.models.{_module_name(schema_of(path))}"
    )
    return getattr(module, def_name[0].upper() + def_name[1:])


def _normalize(value):
    return json.loads(json.dumps(value))


def _params(*, invalid: bool, known: dict[str, str]) -> list:
    return [
        pytest.param(
            path,
            id=fixture_id(path),
            marks=[pytest.mark.xfail(strict=True, reason=known[fixture_id(path)])]
            if fixture_id(path) in known
            else [],
        )
        for path in fixtures(invalid=invalid)
    ]


def _tree(root: Path) -> dict[str, bytes]:
    return {
        p.relative_to(root).as_posix(): p.read_bytes()
        for p in sorted(root.rglob("*.py"))
        if "__pycache__" not in p.parts
    }


def test_models_are_current(tmp_path: Path):
    """Regenerating gives back exactly the committed modules."""
    out = tmp_path / "models"
    subprocess.run(
        [sys.executable, str(GENERATOR), "--out", str(out)],
        check=True,
        capture_output=True,
        text=True,
    )
    fresh, committed = _tree(out), _tree(MODELS)
    assert fresh.keys() == committed.keys(), (
        f"module set differs: only regenerated {sorted(fresh.keys() - committed.keys())}, "
        f"only committed {sorted(committed.keys() - fresh.keys())}; "
        "run `python3 scripts/gen_contract_models.py`"
    )
    stale = [name for name in fresh if fresh[name] != committed[name]]
    assert not stale, (
        f"stale generated modules {stale}; run `python3 scripts/gen_contract_models.py`"
    )


def test_generator_check_mode_passes():
    done = subprocess.run(
        [sys.executable, str(GENERATOR), "--check"], capture_output=True, text=True
    )
    assert done.returncode == 0, done.stdout + done.stderr


@pytest.mark.parametrize("name", SCHEMA_NAMES)
def test_every_schema_has_a_module_with_its_title_class(name: str):
    model = _root_model(name)
    assert issubclass(model, pydantic.BaseModel)


def test_package_import_is_lazy():
    """Importing the package pulls in no generated module."""
    code = (
        "import sys; import runwhen_capability.contracts.models as m; "
        "assert not [k for k in sys.modules if k.startswith(m.__name__ + '.')]"
    )
    subprocess.run([sys.executable, "-c", code], check=True)


@pytest.mark.parametrize("path", _params(invalid=False, known=ROUND_TRIP_KNOWN))
def test_round_trip(path: Path):
    doc = _normalize(load_fixture(path))
    model = _model_of(path).model_validate(doc)
    dumped = _normalize(model.model_dump(mode="json", by_alias=True, exclude_unset=True))
    violations = validate_fixture(path, dumped)
    assert not violations, "\n".join(f"{v.path or '(root)'}: {v.message}" for v in violations)
    assert dumped == doc


@pytest.mark.parametrize("path", _params(invalid=True, known=MODEL_LOOSER_THAN_SCHEMA))
def test_invalid_fixtures_rejected_by_models(path: Path):
    model = _model_of(path)
    with pytest.raises(pydantic.ValidationError):
        model.model_validate(_normalize(load_fixture(path)))


def test_looser_than_schema_entries_are_real_fixtures():
    known = {fixture_id(p) for p in fixtures(invalid=True)} | {
        fixture_id(p) for p in fixtures(invalid=False)
    }
    assert not (set(MODEL_LOOSER_THAN_SCHEMA) | set(ROUND_TRIP_KNOWN)) - known
